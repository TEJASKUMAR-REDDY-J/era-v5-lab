"""Run refreshed-gold tests for every G1 pack without mistaking absent rules for PASS.

Example from repository root:
  python teams/01-data-a/tools/run_harm_suite.py --parquet-dir /path/to/original-packs

This runner never downloads or commits raw packs. It writes only JSON counters,
IDs, and hashes. The parent must first be generated by build_spec_v1.py.
"""
from __future__ import annotations
import argparse
import json
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
TEAM = ROOT / 'teams' / '01-data-a'
SUPPORTED = (
    'code-cpp', 'code-go', 'code-java', 'code-js-ts', 'code-rust',
    'en-dclm', 'en-fineweb-edu', 'en-nemotroncc', 'en-nemotroncc-synth',
)
PENDING = {
    'code-python': 'Canonical code medicines explicitly exclude Python',
    'math-finemath': 'Canonical math medicine and conflict review pending',
    'math-megamath': 'Canonical math medicine and two-reader gold pending',
    'sci-finepdfs': 'Canonical science medicine and conflict review pending',
}
ALL = tuple(dict.fromkeys((*SUPPORTED, *PENDING)))


def run(parquet_dir: Path, report_dir: Path, spec: Path) -> int:
    report_dir.mkdir(parents=True, exist_ok=True)
    results = []
    for pack in ALL:
        record = {'pack_id': pack}
        if pack in PENDING:
            record.update(status='PENDING', reason=PENDING[pack])
        else:
            parquet = parquet_dir / (pack + '.parquet')
            gold = TEAM / 'gold' / (pack + '_gold.csv')
            missing = [str(p) for p in (spec, parquet, gold) if not p.is_file()]
            if missing:
                record.update(status='NOT_EVALUATED', reason='Missing input: ' + ', '.join(missing))
            else:
                report = report_dir / (pack + '_harm.json')
                # Never mistake a prior gold snapshot's JSON for this run.
                report.unlink(missing_ok=True)
                cmd = [sys.executable, str(TEAM/'tools'/'harm_test.py'),
                       '--pack', str(parquet), '--gold', str(gold),
                       '--rules', str(spec), '--rule', 'all', '--report', str(report)]
                try:
                    proc = subprocess.run(cmd, capture_output=True, text=True, timeout=900)
                except subprocess.TimeoutExpired:
                    record.update(status='ERROR', reason='Harm process exceeded 900-second timeout')
                    results.append(record)
                    print(f'{pack:<22} {record["status"]:<15} -')
                    continue
                # Do not leak document content from unpredictable Python failures.
                if report.is_file():
                    try:
                        payload = json.loads(report.read_text(encoding='utf-8'))
                        status = payload.get('status', 'ERROR')
                        record.update(status=status, gold_count=payload.get('gold_count'),
                                      report=str(report), gold_sha256=payload.get('gold_sha256'),
                                      pack_sha256=payload.get('pack_sha256'),
                                      worst_percent=max((float(item['percent']) for item in payload.get('results', [])),default=None))
                        if proc.returncode != {'PASS':0, 'FAIL':1, 'ERROR':2}.get(status, -1):
                            record['status'] = 'ERROR'
                            record['reason'] = 'Process exit did not match report status'
                    except (OSError, ValueError, TypeError, KeyError):
                        record.update(status='ERROR', reason='Malformed JSON report')
                else:
                    record.update(status='ERROR', reason='Harm test returned no report; run that pack manually for diagnostic output')
        results.append(record)
        print(f'{pack:<22} {record["status"]:<15} {record.get("gold_count", "-")}')
    (report_dir/'g1_harm_summary.json').write_text(json.dumps(results, indent=2)+'\n', encoding='utf-8')
    # Never claim a complete 13-pack release while any required pack is pending.
    complete = all(x['status'] == 'PASS' for x in results)
    print('G1 release readiness:', 'READY' if complete else 'INCOMPLETE (expected until pending scopes clear)')
    return 0 if complete else 1


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--parquet-dir', type=Path, required=True)
    parser.add_argument('--report-dir', type=Path, default=TEAM/'reports')
    parser.add_argument('--spec', type=Path, default=TEAM/'spec'/'spec_v1.md')
    args = parser.parse_args(argv)
    return run(args.parquet_dir, args.report_dir, args.spec)


if __name__ == '__main__':
    raise SystemExit(main())
